FIXED_NOW = datetime(2026, 9, 2, 21, 0, tzinfo=UTC)

# The projection is exercised against admin-owned fixtures rather than the
# delivered catalog. Scientific receipts and workload profiles are generated by
# the model-onboarding workstream, so binding these assertions to the shipped
# catalog would make this suite fail whenever that producer regenerates it.
FIXTURES = Path(__file__).resolve().parent / "fixtures/scientific-admin-catalog"
RECEIPTS = FIXTURES / "scientific-source-candidate-receipts.json"
ACADEMIC_READINESS = FIXTURES / "academic-asset-readiness.json"

DELIVERED_CATALOG = Path(__file__).resolve().parents[3] / "catalog/runtime"


def adapter(
    registry: Registry,
    *,
    receipts_file: Path = RECEIPTS,
    **overrides: Path,
) -> ScientificCatalogFileAdapter:
    return ScientificCatalogFileAdapter(
        registry=registry,
        receipts_file=receipts_file,
        clock=lambda: FIXED_NOW,
        **overrides,
    )


async def test_candidate_catalog_is_truthful_about_access_identity_and_cache_state(registry: Registry) -> None:
    snapshot = await adapter(registry).list_models()

    assert snapshot.observed_at == FIXED_NOW
    by_id = {item.model_id: item for item in snapshot.data.items}
    assert sorted(by_id) == ["alphafold3", "rfdiffusion"]

    alpha_fold = by_id["alphafold3"]
    assert alpha_fold.readiness == "candidate"
    assert alpha_fold.access.profile == "academic"
    assert alpha_fold.access.state == "verified"
    assert alpha_fold.access.request_time_license_receipt_required is False
    assert alpha_fold.access.receipt_digest is None
    assert alpha_fold.access.authorization is not None
    assert alpha_fold.access.authorization.use_authorization_status == "Granted"
    assert alpha_fold.access.authorization.execution_authorization_status == "Authorized"
    assert alpha_fold.access.authorization.asset_id == "alphafold3"
    assert alpha_fold.access.formal_license_status == "FormalAcceptancePending"
    assert "Formal acceptance is advisory" in alpha_fold.access.gate
    assert alpha_fold.access.credentials_exposed is False
    assert alpha_fold.access.alternative is not None
    assert alpha_fold.access.alternative.model_id == "openfold3-openbind"
    # No exact fast-start observation is joined to a scientific backend yet, so
    # the tier must stay unobserved rather than inheriting a generic default.
    assert alpha_fold.caching.exact_tier == "not-observed"
    assert alpha_fold.caching.gpu_snapshot == "unavailable"

    # A standard-licence candidate must carry no academic authorization at all.
    rfdiffusion = by_id["rfdiffusion"]
    assert rfdiffusion.backend.backend_id == "rfdiffusion-upstream:native-upstream"
    assert "rfdiffusion-upstream" not in by_id
    assert rfdiffusion.access.profile == "standard"
    assert rfdiffusion.access.state == "not-required"
    assert rfdiffusion.access.authorization is None
    assert rfdiffusion.access.formal_license_status == "not-applicable"
    assert rfdiffusion.qualification.state == "identity-mismatch"
    assert "variant_id" in rfdiffusion.qualification.mismatched

    assert alpha_fold.execution_mode == "scientific-batch"
    assert alpha_fold.interactive_supported is True
    assert [value.value for value in alpha_fold.service_classes] == ["customer-batch", "interactive"]
    assert rfdiffusion.interactive_supported is False


