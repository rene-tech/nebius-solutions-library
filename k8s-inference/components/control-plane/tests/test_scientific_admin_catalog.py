def test_signed_promoted_variant_cannot_override_an_unqualified_candidate_contract(
    registry: Registry,
) -> None:
    runtime_digest = "sha256:" + "7" * 64
    source_revision = "8" * 40
    base = registry.get("rfdiffusion", require_enabled=False)
    promoted = replace(
        base,
        gateway=replace(base.gateway, routable=True, runtime_image_digest=runtime_digest),
        variant_id="rfdiffusion-upstream-portable",
        variant_digest="9" * 64,
        variant_valid_until="2099-01-01T00:00:00Z",
    )

    qualification = _execution_identity_join(
        candidate_id="rfdiffusion-upstream",
        route_scope=CandidateRouteScope(
            lane_id="rfdiffusion",
            variant_ids=frozenset({"rfdiffusion-upstream-portable"}),
            mapped=True,
        ),
        backend_identity="native-upstream",
        operational=promoted,
        execution_identity={
            "model_revision": source_revision,
            "runtime_image_digest": runtime_digest,
        },
    )

    assert qualification.state == "evidence-absent"
    assert qualification.mismatched == []
    assert qualification.compared == ["runtime_image_digest", "variant_id"]
    assert "explicitly remain unqualified" in qualification.reason


